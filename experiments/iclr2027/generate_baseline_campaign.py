@dataclass(frozen=True)
class Condition:
    method: str
    context_size: int
    question_parallelism: int
    # Planning CHF per question and repetition: historical GPT-5-mini spend,
    # converted at 0.80 CHF/USD with 25% contingency (the factors cancel).
    estimated_cost_chf_per_question: float
    memory_reservation_mib: int
    memory_limit_mib: int

    @property
    def label(self) -> str:
        return f"x{'full' if self.context_size == -1 else self.context_size}"


CONDITIONS = (
    Condition("llm", 100, 4, 0.00888, 2_048, 4_096),
    Condition("llm", 500, 4, 0.00866, 4_096, 8_192),
    Condition("codeact", 100, 2, 0.03282, 4_096, 8_192),
    Condition("codeact", 500, 2, 0.03117, 6_144, 12_288),
    Condition("rlm", 100, 1, 0.01534, 8_192, 16_384),
    Condition("rlm", 500, 1, 0.02288, 10_240, 20_480),
    Condition("rlm", -1, 1, 0.01489, 16_384, 30_720),
)


def quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render() -> str:
    lines = [
        "# Generated by generate_baseline_campaign.py; edit the generator, not this file.",
        "schema_version = 1",
        "",
        "[campaign]",
        'name = "iclr2027-baseline-gpt5mini-v1"',
        'project_root = "../.."',
        'artifact_dir = "artifacts/iclr2027-baseline-gpt5mini-v1"',
        "budget_chf = 1500.0",
        "usd_to_chf = 0.80 # Provisional pinned conversion; freeze before the paid run.",
        "require_dataset = true",
        "require_clean_git = true",
        "require_metrics = true",
        "max_parallel_memory_mib = 49152",
        'required_secrets = ["OPENROUTER_API_KEY", "WANDB_API_KEY"]',
        "",
    ]
    for tier, task_ids in TASKS.items():
        for task_id in task_ids:
            for condition in CONDITIONS:
                estimated_cost = (
                    QUESTION_COUNTS[tier][task_id] * condition.estimated_cost_chf_per_question
                )
                run_id = (
                    f"baseline-gpt5mini-{tier}-task{task_id}-{condition.method}-{condition.label}"
                )
                script = f"{tier}/{condition.method}_task{task_id}.py"
                lines.extend(
                    [
                        "[[runs]]",
                        f"id = {quote(run_id)}",
                        f"task = {quote(f'{tier}/task{task_id}')}",
                        f"condition = {quote(f'baseline-{condition.label}')}",
                        f"method = {quote(condition.method)}",
                        f"model = {quote(MODEL)}",
                        f"corpus_size = {quote('full') if condition.context_size == -1 else condition.context_size}",
                        "seed = 42",
                        "repetitions = 5",
                        f"estimated_cost_chf = {estimated_cost:.5f}",
                        f"memory_reservation_mib = {condition.memory_reservation_mib}",
                        f"memory_limit_mib = {condition.memory_limit_mib}",
                        f"question_parallelism = {condition.question_parallelism}",
                        f"env = {{ RXNHAYSTACK_CONTEXT_SIZE = {quote(str(condition.context_size))} }}",
                        f"command = [{', '.join(map(quote, ('uv', 'run', '--frozen', 'python', script)))}]",
                        "",
                    ]
                )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the frozen GPT-5-mini baseline matrix.")
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).with_name("baseline-campaign.toml"),
    )
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"Generated campaign is stale: {args.output}")
        return 0
    args.output.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
