from __future__ import annotations

import argparse
from pathlib import Path

try:
    from .generate_baseline_campaign import CONDITIONS, QUESTION_COUNTS, quote
    from .generate_full_campaign import MODELS, estimated_cost_chf
except ImportError:  # Direct script execution.
    from generate_baseline_campaign import CONDITIONS, QUESTION_COUNTS, quote
    from generate_full_campaign import MODELS, estimated_cost_chf

CAMPAIGN = "iclr2027-gpt5mini-direct-openai-docker-v1"
TASKS = ("16", "17", "17b")
MODEL = next(model for model in MODELS if model.alias == "gpt-5-mini")


def render() -> str:
    lines = [
        "# Generated by generate_gpt_direct_openai_docker_campaign.py; edit the generator.",
        "# These are the 45 Docker-required GPT-5-mini RLM cells absent from full v34.",
        "# Run IDs are distinct because transport changes from OpenRouter to direct OpenAI.",
        "schema_version = 1",
        "",
        "[campaign]",
        f"name = {quote(CAMPAIGN)}",
        'project_root = "../.."',
        f'artifact_dir = "artifacts/{CAMPAIGN}"',
        "budget_chf = 30.0",
        "usd_to_chf = 0.80",
        "require_dataset = true",
        "require_clean_git = true",
        "require_metrics = true",
        "max_parallel_memory_mib = 30720",
        'required_secrets = ["OPENAI_API_KEY", "WANDB_API_KEY"]',
        "",
    ]
    rlm_conditions = [condition for condition in CONDITIONS if condition.method == "rlm"]
    for task_id in TASKS:
        for condition in rlm_conditions:
            estimated_cost = estimated_cost_chf(
                MODEL,
                method="rlm",
                context_size=condition.context_size,
                question_count=QUESTION_COUNTS["tier4"][task_id],
            )
            run_id = f"direct-openai-gpt-5-mini-tier4-task{task_id}-rlm-{condition.label}"
            environment = {
                "RXNHAYSTACK_CONTEXT_SIZE": str(condition.context_size),
                "RXNHAYSTACK_PROVIDER": "openai",
                "RXNHAYSTACK_RLM_MAX_TIMEOUT_SECONDS": "1800",
                "RXNHAYSTACK_RLM_OUTPUT_LIMIT": "4096",
                "RXNHAYSTACK_RLM_REASONING_EFFORT": "low",
                "RXNHAYSTACK_RLM_LOCAL_MEMORY_LIMIT_MIB": "8192",
                "RXNHAYSTACK_RLM_LOCAL_TOOL_MEMORY_LIMIT_MIB": "4096",
            }
            environment_text = ", ".join(
                f"{key} = {quote(value)}" for key, value in environment.items()
            )
            lines.extend(
                [
                    "[[runs]]",
                    f"id = {quote(run_id)}",
                    f'task = "tier4/task{task_id}"',
                    f"condition = {quote(f'full-{condition.label}-direct-openai')}",
                    'method = "rlm"',
                    'model = "gpt-5-mini"',
                    f"corpus_size = {quote('full') if condition.context_size == -1 else condition.context_size}",
                    "seed = 42",
                    "repetitions = 5",
                    f"estimated_cost_chf = {estimated_cost:.6f}",
                    f"memory_reservation_mib = {condition.memory_reservation_mib}",
                    f"memory_limit_mib = {condition.memory_limit_mib}",
                    "question_parallelism = 1",
                    f"env = {{ {environment_text} }}",
                    f'command = ["uv", "run", "--frozen", "python", "tier4/rlm_task{task_id}.py"]',
                    "",
                ]
            )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate direct-OpenAI GPT Docker RLM cells.")
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).with_name("gpt-direct-openai-docker-campaign.toml"),
    )
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"Generated campaign is stale: {args.output}")
        return 0
    args.output.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
