from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path

try:
    from .generate_baseline_campaign import quote
except ImportError:  # Direct script execution.
    from generate_baseline_campaign import quote

USD_TO_CHF = 0.80
REPETITIONS = 5
CHUNK_SIZE = 500
CHUNKS_PER_FULL_CORPUS = 245


@dataclass(frozen=True)
class Model:
    alias: str
    model_id: str
    provider: str
    estimated_cost_chf_per_run: float
    map_parallelism: int


@dataclass(frozen=True)
class Question:
    question_id: str
    task: str


MODELS = (
    Model(
        alias="qwen3.5-397b",
        model_id="RCP-AIaaS/Qwen/Qwen3.5-397B-A17B",
        provider="swissai",
        estimated_cost_chf_per_run=0.0,
        map_parallelism=1,
    ),
    Model(
        alias="gemini-3.7-flash",
        model_id="google/gemini-3.7-flash",
        provider="openrouter",
        estimated_cost_chf_per_run=12.0,
        map_parallelism=4,
    ),
)

QUESTIONS = (
    Question("tier1-task1-q01", "tier1/task1"),
    Question("tier2-task5-weight100-ring1", "tier2/task5"),
    Question("tier3-task10-wittig", "tier3/task10"),
)


def render() -> str:
    lines = [
        "# Generated by generate_flat_map_reduce_experiment.py; edit the generator.",
        "# This experiment is intentionally separate from the six-model benchmark.",
        "schema_version = 1",
        "",
        "[campaign]",
        'name = "iclr2027-flat-map-reduce-v1"',
        'project_root = "../.."',
        'artifact_dir = "artifacts/iclr2027-flat-map-reduce-v1"',
        "budget_chf = 200.0",
        f"usd_to_chf = {USD_TO_CHF:.2f}",
        "require_dataset = true",
        "require_clean_git = true",
        "require_metrics = true",
        "max_parallel_memory_mib = 49152",
        'required_secrets = ["OPENROUTER_API_KEY", "SWISSAI_RESEARCH_API_KEY", "WANDB_API_KEY"]',
        "",
    ]
    command = (
        "uv",
        "run",
        "--frozen",
        "python",
        "experiments/iclr2027/run_flat_map_reduce.py",
    )
    for model in MODELS:
        for question in QUESTIONS:
            run_id = f"flat-map-reduce-{model.alias}-{question.question_id}-xfull-c500"
            env_values = {
                "RXNHAYSTACK_MAP_REDUCE_CHUNK_SIZE": str(CHUNK_SIZE),
                "RXNHAYSTACK_MAP_REDUCE_MAX_PARALLEL": str(model.map_parallelism),
                "RXNHAYSTACK_MAP_REDUCE_OUTPUT_LIMIT": "4096",
                "RXNHAYSTACK_MAP_REDUCE_QUESTION_ID": question.question_id,
                "RXNHAYSTACK_PROVIDER": model.provider,
            }
            if model.provider == "swissai":
                env_values.update(
                    {
                        # The map runner owns the bounded three-attempt policy.
                        "RXNHAYSTACK_SWISSAI_RATE_LIMIT_RETRIES": "0",
                        "RXNHAYSTACK_SWISSAI_REQUESTS_PER_MINUTE": "15",
                    }
                )
            env = ", ".join(f"{key} = {quote(value)}" for key, value in sorted(env_values.items()))
            lines.extend(
                [
                    "[[runs]]",
                    f"id = {quote(run_id)}",
                    f"task = {quote(question.task)}",
                    'condition = "full-corpus-fixed-chunks-500"',
                    'method = "map-reduce"',
                    f"model = {quote(model.model_id)}",
                    'corpus_size = "full"',
                    "seed = 42",
                    f"repetitions = {REPETITIONS}",
                    f"estimated_cost_chf = {model.estimated_cost_chf_per_run:.6f}",
                    "memory_reservation_mib = 4096",
                    "memory_limit_mib = 8192",
                    "question_parallelism = 1",
                    f"env = {{ {env} }}",
                    f"command = [{', '.join(map(quote, command))}]",
                    "",
                ]
            )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the flat map-reduce experiment.")
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).with_name("flat-map-reduce-experiment.toml"),
    )
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"Generated experiment is stale: {args.output}")
        return 0
    args.output.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
