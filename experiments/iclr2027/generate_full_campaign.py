from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path

try:
    from .generate_baseline_campaign import CONDITIONS, QUESTION_COUNTS, TASKS, quote
except ImportError:  # Direct script execution.
    from generate_baseline_campaign import CONDITIONS, QUESTION_COUNTS, TASKS, quote

USD_TO_CHF = 0.80
COST_CONTINGENCY = 1.25

# Historical GPT-5-mini tokens for one repetition of each 100-question condition.
TOKEN_FOOTPRINT = {
    ("llm", 100): (1_046_590, 399_241),
    ("llm", 500): (5_110_997, 236_918),
    ("codeact", 100): (3_931_631, 1_413_160),
    ("codeact", 500): (12_962_386, 1_127_097),
    ("rlm", 100): (4_255_383, 578_759),
    ("rlm", 500): (4_447_854, 940_384),
    ("rlm", -1): (3_288_038, 556_650),
}


@dataclass(frozen=True)
class Model:
    alias: str
    model_id: str
    provider: str
    input_usd_per_million: float = 0.0
    output_usd_per_million: float = 0.0


MODELS = (
    Model(
        "deepseek-v4-flash",
        "RCP-AIaaS/deepseek-ai/DeepSeek-V4-Flash-0731",
        "swissai",
    ),
    Model("glm-5.2", "CSCS-Inference/zai-org/GLM-5.2", "swissai"),
    Model(
        "qwen3.5-397b",
        "RCP-AIaaS/Qwen/Qwen3.5-397B-A17B",
        "swissai",
    ),
    Model("gemini-3.7-flash", "google/gemini-3.7-flash", "openrouter", 0.75, 3.75),
    Model("claude-sonnet-5", "anthropic/claude-sonnet-5", "openrouter", 2.00, 10.00),
    Model("gpt-5-mini", "openai/gpt-5-mini", "openrouter", 0.25, 2.00),
)


def estimated_cost_chf(
    model: Model,
    *,
    method: str,
    context_size: int,
    question_count: int,
) -> float:
    input_tokens, output_tokens = TOKEN_FOOTPRINT[(method, context_size)]
    cost_usd_per_100 = (
        input_tokens * model.input_usd_per_million + output_tokens * model.output_usd_per_million
    ) / 1_000_000
    return cost_usd_per_100 * question_count / 100 * USD_TO_CHF * COST_CONTINGENCY


def render() -> str:
    lines = [
        "# Generated by generate_full_campaign.py; edit the generator, not this file.",
        "# Costs use the submitted GPT-5-mini token footprint and a 25% contingency.",
        "schema_version = 1",
        "",
        "[campaign]",
        'name = "iclr2027-six-model-full-v2"',
        'project_root = "../.."',
        'artifact_dir = "artifacts/iclr2027-six-model-full-v2"',
        "budget_chf = 1500.0",
        f"usd_to_chf = {USD_TO_CHF:.2f}",
        "require_dataset = true",
        "require_clean_git = true",
        "require_metrics = true",
        "max_parallel_memory_mib = 49152",
        'required_secrets = ["OPENROUTER_API_KEY", "SWISSAI_RESEARCH_API_KEY", "WANDB_API_KEY"]',
        "",
    ]
    for model in MODELS:
        for tier, task_ids in TASKS.items():
            for task_id in task_ids:
                for condition in CONDITIONS:
                    context_size = condition.context_size
                    run_id = (
                        f"full-{model.alias}-{tier}-task{task_id}-"
                        f"{condition.method}-{condition.label}"
                    )
                    script = f"{tier}/{condition.method}_task{task_id}.py"
                    cost = estimated_cost_chf(
                        model,
                        method=condition.method,
                        context_size=context_size,
                        question_count=QUESTION_COUNTS[tier][task_id],
                    )
                    env = {
                        "RXNHAYSTACK_CONTEXT_SIZE": str(context_size),
                        "RXNHAYSTACK_PROVIDER": model.provider,
                    }
                    env_text = ", ".join(f"{key} = {quote(value)}" for key, value in env.items())
                    lines.extend(
                        [
                            "[[runs]]",
                            f"id = {quote(run_id)}",
                            f"task = {quote(f'{tier}/task{task_id}')}",
                            f"condition = {quote(f'full-{condition.label}')}",
                            f"method = {quote(condition.method)}",
                            f"model = {quote(model.model_id)}",
                            f"corpus_size = {quote('full') if context_size == -1 else context_size}",
                            "seed = 42",
                            "repetitions = 5",
                            f"estimated_cost_chf = {cost:.6f}",
                            f"memory_reservation_mib = {condition.memory_reservation_mib}",
                            f"memory_limit_mib = {condition.memory_limit_mib}",
                            f"question_parallelism = {condition.question_parallelism}",
                            f"env = {{ {env_text} }}",
                            f"command = [{', '.join(map(quote, ('uv', 'run', '--frozen', 'python', script)))}]",
                            "",
                        ]
                    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the six-model ICLR campaign.")
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).with_name("full-campaign.toml"),
    )
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"Generated campaign is stale: {args.output}")
        return 0
    args.output.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
