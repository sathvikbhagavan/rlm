from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path

try:
    from .generate_baseline_campaign import CONDITIONS, QUESTION_COUNTS, quote
    from .generate_full_campaign import MODELS, estimated_cost_chf
except ImportError:
    from generate_baseline_campaign import CONDITIONS, QUESTION_COUNTS, quote
    from generate_full_campaign import MODELS, estimated_cost_chf

ORACLE_TASKS = (
    ("tier3", "6"),
    ("tier3", "10"),
    ("tier3", "23"),
    ("tier4", "13"),
    ("tier4", "14"),
)
MODEL_ALIASES = ("qwen3.5-397b", "claude-haiku-4.5")
REPETITIONS = 5
USD_TO_CHF = 0.80


@dataclass(frozen=True)
class OracleCondition:
    label: str
    context_size: int
    memory_reservation_mib: int
    memory_limit_mib: int


ORACLE_CONDITIONS = tuple(
    OracleCondition(
        label=condition.label,
        context_size=condition.context_size,
        memory_reservation_mib=condition.memory_reservation_mib,
        memory_limit_mib=condition.memory_limit_mib,
    )
    for condition in CONDITIONS
    if condition.method == "rlm"
)


def selected_models():
    by_alias = {model.alias: model for model in MODELS}
    return tuple(by_alias[alias] for alias in MODEL_ALIASES)


def render_oracle() -> str:
    lines = [
        "# Generated by generate_oracle_predicate_campaign.py; edit the generator.",
        "schema_version = 1",
        "",
        "[campaign]",
        'name = "iclr2027-oracle-predicate-v1"',
        'project_root = "../.."',
        'artifact_dir = "artifacts/iclr2027-oracle-predicate-v1"',
        "budget_chf = 30.0",
        f"usd_to_chf = {USD_TO_CHF:.2f}",
        "require_dataset = true",
        "require_clean_git = true",
        "require_metrics = true",
        "max_parallel_memory_mib = 49152",
        'required_secrets = ["OPENROUTER_API_KEY", "SWISSAI_RESEARCH_API_KEY", "WANDB_API_KEY"]',
        "",
    ]
    for model in selected_models():
        for tier, task_id in ORACLE_TASKS:
            question_count = QUESTION_COUNTS[tier][task_id]
            for condition in ORACLE_CONDITIONS:
                cost = estimated_cost_chf(
                    model,
                    method="rlm",
                    context_size=condition.context_size,
                    question_count=question_count,
                )
                run_id = f"oracle-{model.alias}-{tier}-task{task_id}-{condition.label}"
                env = {
                    "RXNHAYSTACK_CONTEXT_SIZE": str(condition.context_size),
                    "RXNHAYSTACK_ORACLE_PREDICATE": "1",
                    "RXNHAYSTACK_PROVIDER": model.provider,
                    "RXNHAYSTACK_RLM_LOCAL_MEMORY_LIMIT_MIB": "8192",
                    "RXNHAYSTACK_RLM_LOCAL_TOOL_MEMORY_LIMIT_MIB": "4096",
                    "RXNHAYSTACK_RLM_MAX_TIMEOUT_SECONDS": "1800",
                    "RXNHAYSTACK_RLM_OUTPUT_LIMIT": "4096"
                    if model.provider == "openrouter"
                    else "2048",
                }
                if model.provider == "openrouter":
                    env["RXNHAYSTACK_RLM_REASONING_EFFORT"] = "low"
                else:
                    env["RXNHAYSTACK_SWISSAI_RATE_LIMIT_RETRIES"] = "2"
                    env["RXNHAYSTACK_SWISSAI_REQUESTS_PER_MINUTE"] = "15"
                env_text = ", ".join(
                    f"{key} = {quote(value)}" for key, value in sorted(env.items())
                )
                command = ("uv", "run", "--frozen", "python", f"{tier}/rlm_task{task_id}.py")
                lines.extend(
                    [
                        "[[runs]]",
                        f"id = {quote(run_id)}",
                        f"task = {quote(f'{tier}/task{task_id}')}",
                        f"condition = {quote(f'oracle-predicate-{condition.label}')}",
                        'method = "rlm"',
                        f"model = {quote(model.model_id)}",
                        f"corpus_size = {quote('full') if condition.context_size == -1 else condition.context_size}",
                        "seed = 42",
                        f"repetitions = {REPETITIONS}",
                        f"estimated_cost_chf = {cost:.6f}",
                        f"memory_reservation_mib = {condition.memory_reservation_mib}",
                        f"memory_limit_mib = {condition.memory_limit_mib}",
                        "question_parallelism = 1",
                        f"env = {{ {env_text} }}",
                        f"command = [{', '.join(map(quote, command))}]",
                        "",
                    ]
                )
    return "\n".join(lines)


def render_executor() -> str:
    lines = [
        "# Generated by generate_oracle_predicate_campaign.py; edit the generator.",
        "schema_version = 1",
        "",
        "[campaign]",
        'name = "iclr2027-oracle-executor-v1"',
        'project_root = "../.."',
        'artifact_dir = "artifacts/iclr2027-oracle-executor-v1"',
        "budget_chf = 0.0",
        f"usd_to_chf = {USD_TO_CHF:.2f}",
        "require_dataset = true",
        "require_clean_git = true",
        "require_metrics = true",
        "max_parallel_memory_mib = 49152",
        "required_secrets = []",
        "",
    ]
    for tier, task_id in ORACLE_TASKS:
        for condition in ORACLE_CONDITIONS:
            run_id = f"oracle-executor-{tier}-task{task_id}-{condition.label}"
            command = (
                "uv",
                "run",
                "--frozen",
                "python",
                "experiments/iclr2027/oracle_executor.py",
                "--tier",
                tier,
                "--task",
                task_id,
            )
            lines.extend(
                [
                    "[[runs]]",
                    f"id = {quote(run_id)}",
                    f"task = {quote(f'{tier}/task{task_id}')}",
                    f"condition = {quote(f'oracle-executor-{condition.label}')}",
                    'method = "deterministic"',
                    'model = "none"',
                    f"corpus_size = {quote('full') if condition.context_size == -1 else condition.context_size}",
                    "seed = 42",
                    "repetitions = 1",
                    "estimated_cost_chf = 0.0",
                    f"memory_reservation_mib = {condition.memory_reservation_mib}",
                    f"memory_limit_mib = {condition.memory_limit_mib}",
                    "question_parallelism = 1",
                    f'env = {{ RXNHAYSTACK_CONTEXT_SIZE = {quote(str(condition.context_size))}, RXNHAYSTACK_ORACLE_EXECUTOR = "1" }}',
                    f"command = [{', '.join(map(quote, command))}]",
                    "",
                ]
            )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate oracle-predicate controls.")
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--oracle-output",
        type=Path,
        default=Path(__file__).with_name("oracle-predicate-campaign.toml"),
    )
    parser.add_argument(
        "--executor-output",
        type=Path,
        default=Path(__file__).with_name("oracle-executor-campaign.toml"),
    )
    args = parser.parse_args()
    outputs = {
        args.oracle_output: render_oracle(),
        args.executor_output: render_executor(),
    }
    if args.check:
        stale = [
            path
            for path, expected in outputs.items()
            if not path.is_file() or path.read_text() != expected
        ]
        if stale:
            raise SystemExit("Generated oracle files are stale: " + ", ".join(map(str, stale)))
        return 0
    for path, expected in outputs.items():
        path.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
