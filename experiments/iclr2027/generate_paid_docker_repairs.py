from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path

from rxnhaystack.manifest import PlannedRun, load_manifest

try:
    from .generate_baseline_campaign import QUESTION_COUNTS, quote
except ImportError:  # Direct script execution.
    from generate_baseline_campaign import QUESTION_COUNTS, quote


DIRECTORY = Path(__file__).resolve().parent
SOURCE = DIRECTORY / "full-campaign.toml"


@dataclass(frozen=True)
class RepairDefinition:
    campaign: str
    output: Path
    model: str
    source_run_ids: tuple[str, ...]
    per_question_cost_chf: float
    budget_chf: float


GEMINI_SOURCE_RUN_IDS = (
    "full-gemini-3.7-flash-tier4-task16-rlm-xfull-r02",
    "full-gemini-3.7-flash-tier4-task16-rlm-xfull-r03",
    "full-gemini-3.7-flash-tier4-task16-rlm-xfull-r04",
    "full-gemini-3.7-flash-tier4-task16-rlm-xfull-r05",
    "full-gemini-3.7-flash-tier4-task17-rlm-xfull-r04",
    "full-gemini-3.7-flash-tier4-task17-rlm-xfull-r05",
    "full-gemini-3.7-flash-tier4-task17b-rlm-xfull-r04",
    "full-gemini-3.7-flash-tier4-task17b-rlm-xfull-r05",
)


def glm_source_run_ids() -> tuple[str, ...]:
    return tuple(
        f"full-glm-5.2-tier4-{task}-rlm-{context}-r{repetition:02d}"
        for context in ("x100", "x500", "xfull")
        for task in ("task17", "task17b", "task16")
        for repetition in range(1, 6)
    )


DEFINITIONS = (
    RepairDefinition(
        campaign="iclr2027-gemini-paid-openrouter-docker-repair-v1",
        output=DIRECTORY / "gemini-paid-openrouter-docker-repair.toml",
        model="google/gemini-3.7-flash",
        source_run_ids=GEMINI_SOURCE_RUN_IDS,
        # Historical successful Gemini full-context cells imply roughly CHF 12
        # for this exact set. CHF 0.30/question gives a conservative CHF 18.
        per_question_cost_chf=0.30,
        budget_chf=25.0,
    ),
    RepairDefinition(
        campaign="iclr2027-glm-paid-openrouter-docker-v1",
        output=DIRECTORY / "glm-paid-openrouter-docker.toml",
        model="z-ai/glm-5.2",
        source_run_ids=glm_source_run_ids(),
        per_question_cost_chf=0.30,
        budget_chf=100.0,
    ),
)


def selected_source_runs(definition: RepairDefinition, source: Path = SOURCE) -> list[PlannedRun]:
    manifest = load_manifest(source)
    by_id = {run.run_id: run for run in manifest.runs}
    missing = set(definition.source_run_ids) - by_id.keys()
    if missing:
        raise ValueError(f"Source manifest is missing repair runs: {sorted(missing)}")
    return [by_id[run_id] for run_id in definition.source_run_ids]


def render(definition: RepairDefinition, source_runs: list[PlannedRun]) -> str:
    lines = [
        "# Generated by generate_paid_docker_repairs.py from full-campaign.toml.",
        "# Each cell is attempted once by the local Docker queue; failures are not retried.",
        "schema_version = 1",
        "",
        "[campaign]",
        f"name = {quote(definition.campaign)}",
        'project_root = "../.."',
        f'artifact_dir = "artifacts/{definition.campaign}"',
        f"budget_chf = {definition.budget_chf:.1f}",
        "usd_to_chf = 0.80",
        "require_dataset = true",
        "require_clean_git = true",
        "require_metrics = true",
        "max_parallel_memory_mib = 49152",
        'required_secrets = ["OPENROUTER_API_KEY", "WANDB_API_KEY"]',
        "",
    ]
    for source in source_runs:
        tier, task = source.task.split("/")
        task_id = task.removeprefix("task")
        estimated_cost = QUESTION_COUNTS[tier][task_id] * definition.per_question_cost_chf
        environment = {
            key: value
            for key, value in source.env.items()
            if not key.startswith("RXNHAYSTACK_SWISSAI_")
        }
        environment.update(
            {
                "RXNHAYSTACK_PROVIDER": "openrouter",
                "RXNHAYSTACK_SOURCE_RUN_ID": source.run_id,
            }
        )
        # Paid OpenRouter endpoints support the common RLM response allowance.
        environment["RXNHAYSTACK_RLM_OUTPUT_LIMIT"] = "4096"
        environment_text = ", ".join(
            f"{key} = {quote(value)}" for key, value in sorted(environment.items())
        )
        command = ", ".join(quote(part) for part in source.command)
        lines.extend(
            [
                "[[runs]]",
                f"id = {quote(f'paid-openrouter-{source.run_id}')}",
                f"task = {quote(source.task)}",
                f"condition = {quote(f'paid-openrouter-{source.condition}')}",
                f"method = {quote(source.method)}",
                f"model = {quote(definition.model)}",
                f"corpus_size = {quote(source.corpus_size) if isinstance(source.corpus_size, str) else source.corpus_size}",
                f"seed = {source.seed}",
                "repetitions = 1",
                f"estimated_cost_chf = {estimated_cost:.6f}",
                f"memory_reservation_mib = {source.memory_reservation_mib}",
                f"memory_limit_mib = {source.memory_limit_mib}",
                f"question_parallelism = {source.question_parallelism}",
                f"env = {{ {environment_text} }}",
                f"command = [{command}]",
                "",
            ]
        )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate paid Docker repair experiments.")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for definition in DEFINITIONS:
        rendered = render(definition, selected_source_runs(definition))
        if args.check:
            if not definition.output.exists() or definition.output.read_text() != rendered:
                raise SystemExit(f"{definition.output} is stale; regenerate it")
            print(f"Verified {definition.output}")
        else:
            definition.output.write_text(rendered, encoding="utf-8")
            print(f"Wrote {definition.output} with {len(definition.source_run_ids)} exact cells")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
