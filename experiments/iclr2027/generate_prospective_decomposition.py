from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path

try:
    from .generate_baseline_campaign import quote
except ImportError:  # Direct script execution.
    from generate_baseline_campaign import quote


QUESTION_IDS = (
    "pyrimidine_piperazine",
    "lactam_dipeptide",
    "benzamide_pyrazole",
)
PROMPT_CONDITIONS = ("name_only", "structure_only", "structure_plus_class")
CLASS_LABELS_AUTHOR_APPROVED = False


@dataclass(frozen=True)
class Model:
    alias: str
    model_id: str
    provider: str
    estimated_cost_chf_per_repetition: float


MODELS = (
    Model(
        alias="qwen3.5-397b",
        model_id="RCP-AIaaS/Qwen/Qwen3.5-397B-A17B",
        provider="swissai",
        estimated_cost_chf_per_repetition=0.0,
    ),
    Model(
        alias="claude-haiku-4.5",
        model_id="anthropic/claude-haiku-4.5",
        provider="openrouter",
        # Three of Task 16's ten questions, scaled from the full-campaign
        # Task-16 RLM estimate and retaining its existing contingency.
        estimated_cost_chf_per_repetition=0.182139,
    ),
)


def render() -> str:
    lines = [
        "# Generated by generate_prospective_decomposition.py; edit the generator, not this file.",
        "# structure_plus_class is deliberately held pending author-chemist label approval.",
        "schema_version = 1",
        "",
        "[campaign]",
        'name = "iclr2027-task16-prospective-decomposition-v1"',
        'project_root = "../.."',
        'artifact_dir = "artifacts/iclr2027-task16-prospective-decomposition-v1"',
        "budget_chf = 15.0",
        "usd_to_chf = 0.80",
        "require_dataset = true",
        "require_clean_git = true",
        "require_metrics = true",
        "max_parallel_memory_mib = 61440",
        'required_secrets = ["OPENROUTER_API_KEY", "SWISSAI_RESEARCH_API_KEY", "WANDB_API_KEY"]',
        "",
    ]
    for model in MODELS:
        for condition in PROMPT_CONDITIONS:
            env = {
                "RXNHAYSTACK_CONTEXT_SIZE": "-1",
                "RXNHAYSTACK_PROVIDER": model.provider,
                "RXNHAYSTACK_TASK16_PROMPT_CONDITION": condition,
                "RXNHAYSTACK_TASK16_QUESTION_IDS": ",".join(QUESTION_IDS),
                "RXNHAYSTACK_TASK16_EXCLUDE_ALL_TARGET_PRODUCTS": "1",
                "RXNHAYSTACK_TASK16_CLASS_LABELS_AUTHOR_APPROVED": (
                    "1" if CLASS_LABELS_AUTHOR_APPROVED else "0"
                ),
                "RXNHAYSTACK_RLM_MAX_TIMEOUT_SECONDS": "1800",
                "RXNHAYSTACK_RLM_LOCAL_MEMORY_LIMIT_MIB": "8192",
                "RXNHAYSTACK_RLM_LOCAL_TOOL_MEMORY_LIMIT_MIB": "4096",
            }
            if model.provider == "swissai":
                env.update(
                    {
                        "RXNHAYSTACK_SWISSAI_REQUESTS_PER_MINUTE": "15",
                        "RXNHAYSTACK_SWISSAI_RATE_LIMIT_RETRIES": "2",
                        "RXNHAYSTACK_RLM_OUTPUT_LIMIT": "2048",
                    }
                )
            else:
                env.update(
                    {
                        "RXNHAYSTACK_RLM_OUTPUT_LIMIT": "4096",
                        "RXNHAYSTACK_RLM_REASONING_EFFORT": "low",
                    }
                )
            env_text = ", ".join(f"{key} = {quote(value)}" for key, value in env.items())
            lines.extend(
                [
                    "[[runs]]",
                    f"id = {quote(f'prospective-{model.alias}-task16-{condition}-rlm-xfull')}",
                    'task = "tier4/task16-prospective-decomposition"',
                    f"condition = {quote(condition)}",
                    'method = "rlm"',
                    f"model = {quote(model.model_id)}",
                    'corpus_size = "full"',
                    "seed = 42",
                    "repetitions = 5",
                    f"estimated_cost_chf = {model.estimated_cost_chf_per_repetition:.6f}",
                    "memory_reservation_mib = 28672",
                    "memory_limit_mib = 30720",
                    "question_parallelism = 1",
                    f"env = {{ {env_text} }}",
                    'command = ["uv", "run", "--frozen", "python", "tier4/rlm_task16.py"]',
                    "",
                ]
            )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate the Task-16 name/structure/transformation-class control."
    )
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).with_name("prospective-decomposition.toml"),
    )
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"Generated experiment definition is stale: {args.output}")
        return 0
    args.output.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
