from __future__ import annotations

import argparse
from pathlib import Path

from rxnhaystack.manifest import PlannedRun, load_manifest

try:
    from .generate_baseline_campaign import QUESTION_COUNTS, quote
except ImportError:  # Direct script execution.
    from generate_baseline_campaign import QUESTION_COUNTS, quote


DIRECTORY = Path(__file__).resolve().parent
SOURCE = DIRECTORY / "full-campaign.toml"
OUTPUT = DIRECTORY / "gpt-rlm-x1000-docker.toml"
SOURCE_MODEL = "openai/gpt-5-mini"
CAMPAIGN = "iclr2027-gpt5mini-rlm-x1000-docker-v1"
TASKS = frozenset({"tier4/task16", "tier4/task17", "tier4/task17b"})
PER_QUESTION_COST_CHF = 0.015


def source_runs(source: Path = SOURCE) -> list[PlannedRun]:
    manifest = load_manifest(source)
    selected = [
        run
        for run in manifest.runs
        if run.model == SOURCE_MODEL
        and run.method == "rlm"
        and run.corpus_size == 500
        and run.repetition == 1
        and run.task in TASKS
    ]
    if len(selected) != 3:
        raise ValueError(
            f"Expected three GPT-5-mini Docker task definitions; found {len(selected)}"
        )
    return sorted(selected, key=lambda run: run.run_id)


def render(runs: list[PlannedRun] | None = None) -> str:
    selected = runs or source_runs()
    lines = [
        "# Generated by generate_gpt_rlm_x1000_docker.py from full-campaign.toml.",
        "# Completes the 15 Docker cells missing from the 135-cell Jed x1000 RLM run.",
        "schema_version = 1",
        "",
        "[campaign]",
        f"name = {quote(CAMPAIGN)}",
        'project_root = "../.."',
        f'artifact_dir = "artifacts/{CAMPAIGN}"',
        "budget_chf = 8.0",
        "usd_to_chf = 0.80",
        "require_dataset = true",
        "require_clean_git = true",
        "require_metrics = true",
        "max_parallel_memory_mib = 30720",
        'required_secrets = ["OPENAI_API_KEY", "WANDB_API_KEY"]',
        "",
    ]
    for source in selected:
        tier, task = source.task.split("/")
        task_id = task.removeprefix("task")
        run_id = source.base_id.replace(
            "full-gpt-5-mini-", "x1000-direct-openai-full-gpt-5-mini-"
        ).replace("-x500", "-x1000")
        environment = {
            key: value
            for key, value in source.env.items()
            if key not in {"RXNHAYSTACK_OPENROUTER_MIN_INTERVAL_SECONDS"}
        }
        environment.update(
            {
                "RXNHAYSTACK_CONTEXT_SIZE": "1000",
                "RXNHAYSTACK_PROVIDER": "openai",
                "RXNHAYSTACK_RLM_MAX_TIMEOUT_SECONDS": "1800",
                "RXNHAYSTACK_RLM_OUTPUT_LIMIT": "4096",
                "RXNHAYSTACK_RLM_REASONING_EFFORT": "low",
                "RXNHAYSTACK_SOURCE_RUN_ID": source.run_id,
            }
        )
        environment_text = ", ".join(
            f"{key} = {quote(value)}" for key, value in sorted(environment.items())
        )
        command = ", ".join(quote(part) for part in source.command)
        estimated_cost = QUESTION_COUNTS[tier][task_id] * PER_QUESTION_COST_CHF
        lines.extend(
            [
                "[[runs]]",
                f"id = {quote(run_id)}",
                f"task = {quote(source.task)}",
                'condition = "direct-openai-x1000"',
                'method = "rlm"',
                'model = "gpt-5-mini"',
                "corpus_size = 1000",
                f"seed = {source.seed}",
                "repetitions = 5",
                f"estimated_cost_chf = {estimated_cost:.6f}",
                f"memory_reservation_mib = {source.memory_reservation_mib}",
                f"memory_limit_mib = {source.memory_limit_mib}",
                f"question_parallelism = {source.question_parallelism}",
                f"env = {{ {environment_text} }}",
                f"command = [{command}]",
                "",
            ]
        )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate GPT-5-mini Docker RLM x1000 cells.")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"Generated experiment is stale: {args.output}")
        return 0
    args.output.write_text(expected, encoding="utf-8")
    print(f"Wrote {args.output} with 15 cells")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
