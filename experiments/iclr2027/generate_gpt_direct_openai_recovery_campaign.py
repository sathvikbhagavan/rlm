from __future__ import annotations

import argparse
from pathlib import Path

try:
    from .generate_baseline_campaign import CONDITIONS, QUESTION_COUNTS, quote
    from .generate_full_campaign import MODELS, estimated_cost_chf
except ImportError:  # Direct script execution.
    from generate_baseline_campaign import CONDITIONS, QUESTION_COUNTS, quote
    from generate_full_campaign import MODELS, estimated_cost_chf


CAMPAIGN = "iclr2027-gpt5mini-direct-openai-recovery-v1"
MODEL = next(model for model in MODELS if model.alias == "gpt-5-mini")

# These are exactly the failed non-Docker GPT-5-mini cells in the Kuma v34
# ledger on 2026-09-19. The original repetition is retained in each base ID.
SOURCE_CELLS = (
    *(f"tier4-task13-xfull-r{rep:02d}" for rep in (1, 2)),
    *(f"tier4-task14-xfull-r{rep:02d}" for rep in (2, 3, 4, 5)),
    *(
        f"tier4-task15-x{context}-r{rep:02d}"
        for context in (100, 500, "full")
        for rep in range(1, 6)
    ),
)


def parse_cell(cell: str) -> tuple[str, int, int]:
    _, task_part, context_part, repetition_part = cell.split("-")
    context_text = context_part.removeprefix("x")
    context = -1 if context_text == "full" else int(context_text)
    return task_part.removeprefix("task"), context, int(repetition_part.removeprefix("r"))


def render() -> str:
    lines = [
        "# Generated by generate_gpt_direct_openai_recovery_campaign.py; edit the generator.",
        "# Exactly 21 failed GPT-5-mini non-Docker RLM cells, rerouted around OpenRouter.",
        "schema_version = 1",
        "",
        "[campaign]",
        f"name = {quote(CAMPAIGN)}",
        'project_root = "../.."',
        f'artifact_dir = "artifacts/{CAMPAIGN}"',
        "budget_chf = 20.0",
        "usd_to_chf = 0.80",
        "require_dataset = true",
        "require_clean_git = true",
        "require_metrics = true",
        "max_parallel_memory_mib = 30720",
        'required_secrets = ["OPENAI_API_KEY", "WANDB_API_KEY"]',
        "",
    ]
    by_context = {condition.context_size: condition for condition in CONDITIONS if condition.method == "rlm"}
    for cell in SOURCE_CELLS:
        task_id, context_size, source_repetition = parse_cell(cell)
        condition = by_context[context_size]
        source_run = (
            f"full-gpt-5-mini-tier4-task{task_id}-rlm-{condition.label}-r{source_repetition:02d}"
        )
        run_id = f"direct-openai-recovery-{source_run}"
        cost = estimated_cost_chf(
            MODEL,
            method="rlm",
            context_size=context_size,
            question_count=QUESTION_COUNTS["tier4"][task_id],
        )
        tool_memory = "8192" if task_id == "13" else "4096"
        env = {
            "RXNHAYSTACK_CONTEXT_SIZE": str(context_size),
            "RXNHAYSTACK_PROVIDER": "openai",
            "RXNHAYSTACK_RLM_MAX_TIMEOUT_SECONDS": "1800",
            "RXNHAYSTACK_RLM_OUTPUT_LIMIT": "4096",
            "RXNHAYSTACK_RLM_REASONING_EFFORT": "low",
            "RXNHAYSTACK_RLM_LOCAL_MEMORY_LIMIT_MIB": "8192",
            "RXNHAYSTACK_RLM_LOCAL_TOOL_MEMORY_LIMIT_MIB": tool_memory,
            "RXNHAYSTACK_SOURCE_RUN_ID": source_run,
        }
        env_text = ", ".join(f"{key} = {quote(value)}" for key, value in env.items())
        lines.extend(
            [
                "[[runs]]",
                f"id = {quote(run_id)}",
                f'task = "tier4/task{task_id}"',
                f"condition = {quote(f'recovery-{condition.label}-direct-openai')}",
                'method = "rlm"',
                'model = "gpt-5-mini"',
                f"corpus_size = {quote('full') if context_size == -1 else context_size}",
                "seed = 42",
                "repetitions = 1",
                f"estimated_cost_chf = {cost:.6f}",
                f"memory_reservation_mib = {condition.memory_reservation_mib}",
                f"memory_limit_mib = {condition.memory_limit_mib}",
                "question_parallelism = 1",
                f"env = {{ {env_text} }}",
                f'command = ["uv", "run", "--frozen", "python", "tier4/rlm_task{task_id}.py"]',
                "",
            ]
        )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate direct-OpenAI GPT recovery cells.")
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).with_name("gpt-direct-openai-recovery-campaign.toml"),
    )
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"Generated campaign is stale: {args.output}")
        return 0
    args.output.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
