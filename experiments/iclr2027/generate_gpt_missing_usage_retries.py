from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path

from rxnhaystack.manifest import ExperimentManifest, PlannedRun, load_manifest

HERE = Path(__file__).resolve().parent
FULL_SOURCE = HERE / "full-campaign.toml"
MATCHED_SOURCE = HERE / "matched-cardinality-campaign.toml"
FULL_OUTPUT = HERE / "retry-gpt5mini-full-missing-usage.toml"
MATCHED_OUTPUT = HERE / "retry-gpt5mini-matched-missing-usage.toml"


@dataclass(frozen=True)
class FailureGroup:
    base_id: str
    repetition_start: int = 1
    repetitions: int = 5


FULL_FAILURES = (
    FailureGroup("full-gpt-5-mini-tier4-task14-rlm-xfull", 2, 4),
    FailureGroup("full-gpt-5-mini-tier4-task15-rlm-x100"),
    FailureGroup("full-gpt-5-mini-tier4-task15-rlm-x500"),
    FailureGroup("full-gpt-5-mini-tier4-task15-rlm-xfull"),
)

MATCHED_CONDITIONS = (
    "cardinality-x5000-k20",
    "cardinality-x5000-k5",
    "scale-x100-k1",
    "scale-x500-k1",
    "scale-x5000-k1",
    "scale-x50000-k1",
    "scale-xfull-k1",
)
MATCHED_TASKS = ("8", "9", "10", "10b", "13", "14", "15", "17", "18", "20", "21", "22", "23", "24")
MATCHED_FAILURES = (
    FailureGroup("matched-gpt-5-mini-tier3-task7-cardinality-x5000-k20"),
    FailureGroup("matched-gpt-5-mini-tier3-task7-cardinality-x5000-k5"),
    FailureGroup("matched-gpt-5-mini-tier3-task7-scale-xfull-k1"),
    *(
        FailureGroup(f"matched-gpt-5-mini-tier3-task{task}-{condition}")
        for task in MATCHED_TASKS
        for condition in MATCHED_CONDITIONS
    ),
)


def quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def source_run(manifest: ExperimentManifest, group: FailureGroup) -> PlannedRun:
    matches = [run for run in manifest.runs if run.base_id == group.base_id]
    if len(matches) != 5:
        raise ValueError(
            f"Expected five source repetitions for {group.base_id}; found {len(matches)}"
        )
    expected = set(range(group.repetition_start, group.repetition_start + group.repetitions))
    available = {run.repetition for run in matches}
    if not expected <= available:
        raise ValueError(f"Missing source repetitions for {group.base_id}: {expected - available}")
    return matches[0]


def render(
    source: ExperimentManifest,
    groups: tuple[FailureGroup, ...],
    *,
    campaign_name: str,
    budget_chf: float,
) -> str:
    expanded_count = sum(group.repetitions for group in groups)
    lines = [
        "# Generated by generate_gpt_missing_usage_retries.py.",
        f"# Contains exactly {expanded_count} audited missing-usage failures and no successes.",
        "schema_version = 1",
        "",
        "[campaign]",
        f"name = {quote(campaign_name)}",
        'project_root = "../.."',
        f"artifact_dir = {quote(f'artifacts/{campaign_name}')}",
        f"budget_chf = {budget_chf:.2f}",
        f"usd_to_chf = {source.campaign.usd_to_chf:.2f}",
        "require_dataset = true",
        "require_clean_git = true",
        "require_metrics = true",
        f"max_parallel_memory_mib = {source.campaign.max_parallel_memory_mib}",
        'required_secrets = ["OPENROUTER_API_KEY", "WANDB_API_KEY"]',
        "",
    ]
    for group in groups:
        run = source_run(source, group)
        retry_base_id = f"retry-usagefix-{group.base_id}"
        env = ", ".join(f"{key} = {quote(value)}" for key, value in run.env.items())
        command = ", ".join(quote(value) for value in run.command)
        corpus_size = (
            quote(run.corpus_size) if isinstance(run.corpus_size, str) else str(run.corpus_size)
        )
        lines.extend(
            [
                "[[runs]]",
                f"id = {quote(retry_base_id)}",
                f"source_run_id = {quote(group.base_id + '-r{repetition:02d}')}",
                f"task = {quote(run.task)}",
                f"condition = {quote(run.condition)}",
                f"method = {quote(run.method)}",
                f"model = {quote(run.model)}",
                f"corpus_size = {corpus_size}",
            ]
        )
        if run.positive_cardinality is not None:
            lines.append(f"positive_cardinality = {run.positive_cardinality}")
        lines.extend(
            [
                f"seed = {run.seed}",
                f"repetition_start = {group.repetition_start}",
                f"repetitions = {group.repetitions}",
                f"estimated_cost_chf = {run.estimated_cost_chf:.6f}",
                f"memory_reservation_mib = {run.memory_reservation_mib}",
                f"memory_limit_mib = {run.memory_limit_mib}",
                f"question_parallelism = {run.question_parallelism}",
                f"env = {{ {env} }}",
                f"command = [{command}]",
                "",
            ]
        )
    return "\n".join(lines)


def outputs() -> tuple[tuple[Path, str], ...]:
    full = load_manifest(FULL_SOURCE)
    matched = load_manifest(MATCHED_SOURCE)
    return (
        (
            FULL_OUTPUT,
            render(
                full,
                FULL_FAILURES,
                campaign_name="iclr2027-gpt5mini-full-missing-usage-retry-v1",
                budget_chf=5.00,
            ),
        ),
        (
            MATCHED_OUTPUT,
            render(
                matched,
                MATCHED_FAILURES,
                campaign_name="iclr2027-gpt5mini-matched-missing-usage-retry-v1",
                budget_chf=97.00,
            ),
        ),
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate audited GPT missing-usage retries.")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in outputs():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                raise SystemExit(f"Generated retry campaign is stale: {path}")
        else:
            path.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
