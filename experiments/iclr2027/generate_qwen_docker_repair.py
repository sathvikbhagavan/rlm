from __future__ import annotations

import argparse
from pathlib import Path

from rxnhaystack.manifest import PlannedRun, load_manifest

try:
    from .generate_baseline_campaign import QUESTION_COUNTS, quote
except ImportError:  # Direct script execution.
    from generate_baseline_campaign import QUESTION_COUNTS, quote


CAMPAIGN = "iclr2027-qwen-paid-openrouter-docker-repair-v1"
OPENROUTER_MODEL = "qwen/qwen3.5-397b-a17b"
OUTPUT = Path(__file__).with_name("qwen-paid-openrouter-docker-repair.toml")
SOURCE = Path(__file__).with_name("full-campaign.toml")
SOURCE_RUN_IDS = (
    "full-qwen3.5-397b-tier4-task16-rlm-xfull-r02",
    "full-qwen3.5-397b-tier4-task16-rlm-xfull-r03",
    "full-qwen3.5-397b-tier4-task16-rlm-xfull-r04",
    "full-qwen3.5-397b-tier4-task16-rlm-xfull-r05",
    "full-qwen3.5-397b-tier4-task17b-rlm-xfull-r03",
    "full-qwen3.5-397b-tier4-task17b-rlm-xfull-r04",
)


def selected_source_runs(source: Path = SOURCE) -> list[PlannedRun]:
    manifest = load_manifest(source)
    by_id = {run.run_id: run for run in manifest.runs}
    missing = set(SOURCE_RUN_IDS) - by_id.keys()
    if missing:
        raise ValueError(f"Source manifest is missing repair runs: {sorted(missing)}")
    return [by_id[run_id] for run_id in SOURCE_RUN_IDS]


def render(source_runs: list[PlannedRun]) -> str:
    lines = [
        "# Generated by generate_qwen_docker_repair.py from full-campaign.toml.",
        "# These are the six exact full-benchmark cells absent from Sathvik's archive.",
        "schema_version = 1",
        "",
        "[campaign]",
        f"name = {quote(CAMPAIGN)}",
        'project_root = "../.."',
        f'artifact_dir = "artifacts/{CAMPAIGN}"',
        "budget_chf = 15.0",
        "usd_to_chf = 0.80",
        "require_dataset = true",
        "require_clean_git = true",
        "require_metrics = true",
        "max_parallel_memory_mib = 49152",
        'required_secrets = ["OPENROUTER_API_KEY", "WANDB_API_KEY"]',
        "",
    ]
    for source in source_runs:
        tier, task = source.task.split("/")
        task_id = task.removeprefix("task")
        # CHF 0.20 per trajectory is deliberately conservative for this paid model.
        estimated_cost = QUESTION_COUNTS[tier][task_id] * 0.20
        environment = {
            key: value
            for key, value in source.env.items()
            if not key.startswith("RXNHAYSTACK_SWISSAI_")
        }
        environment.update(
            {
                "RXNHAYSTACK_PROVIDER": "openrouter",
                "RXNHAYSTACK_SOURCE_RUN_ID": source.run_id,
            }
        )
        environment_text = ", ".join(
            f"{key} = {quote(value)}" for key, value in sorted(environment.items())
        )
        command = ", ".join(quote(part) for part in source.command)
        lines.extend(
            [
                "[[runs]]",
                f"id = {quote(f'paid-openrouter-{source.run_id}')}",
                f"task = {quote(source.task)}",
                f"condition = {quote(f'paid-openrouter-{source.condition}')}",
                f"method = {quote(source.method)}",
                f"model = {quote(OPENROUTER_MODEL)}",
                'corpus_size = "full"',
                f"seed = {source.seed}",
                "repetitions = 1",
                f"estimated_cost_chf = {estimated_cost:.6f}",
                f"memory_reservation_mib = {source.memory_reservation_mib}",
                f"memory_limit_mib = {source.memory_limit_mib}",
                f"question_parallelism = {source.question_parallelism}",
                f"env = {{ {environment_text} }}",
                f"command = [{command}]",
                "",
            ]
        )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the six-cell Qwen Docker repair.")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render(selected_source_runs())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != rendered:
            raise SystemExit(f"{OUTPUT} is stale; regenerate it")
        print(f"Verified {OUTPUT}")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"Wrote {OUTPUT} with {len(SOURCE_RUN_IDS)} exact repair cells")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
